#!/usr/bin/env node
// Import the existing canonical JSON manifest, never a hand-maintained matrix.
// Network resolution happens before Astro/Bazel; the static build stays offline.
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { fileURLToPath } from "node:url";

export const repository = "meridian-ux/meridian";
export const manifestPath = "schemas/conformance/coverage.json";
export function validate(manifest) {
  if (!manifest || !Object.keys(manifest.renderers ?? {}).length || !Object.keys(manifest.arms ?? {}).length) {
    throw new Error("coverage manifest needs nonempty renderers and arms");
  }
  const sections = [{ arms: manifest.arms, renderers: Object.keys(manifest.renderers) },
    ...Object.values(manifest.modalities ?? {}).map(section => ({
      arms: section.arms, renderers: Object.keys(Object.values(section.arms ?? {})[0]?.renderers ?? {}),
    }))];
  for (const section of sections) {
    if (!section.renderers.length || !Object.keys(section.arms ?? {}).length) throw new Error("empty modality");
    for (const [arm, entry] of Object.entries(section.arms)) {
      const ids = Object.keys(entry.renderers ?? {});
      if (ids.length !== section.renderers.length || section.renderers.some(id => !ids.includes(id))) {
        throw new Error(`${arm}: incomplete renderer cells`);
      }
      for (const cell of Object.values(entry.renderers)) {
        if (!Object.hasOwn(manifest.statuses ?? {}, cell.status)) throw new Error(`${arm}: unknown status ${cell.status}`);
        if (cell.status !== "renders" && !cell.reason) throw new Error(`${arm}: non-rendering cell needs reason`);
      }
    }
  }
  return manifest;
}

export function sourceModule(revision) {
  if (!/^[0-9a-f]{40}$/.test(revision)) throw new Error("source revision must be a full Git commit SHA");
  return `// Generated by tools/sync_conformance.mjs; do not edit.\nexport const conformanceSource = ${JSON.stringify({ repository, revision, path: manifestPath }, null, 2)} as const;\n`;
}

async function json(url) {
  const response = await fetch(url, { signal: AbortSignal.timeout(30_000), headers: { Accept: "application/vnd.github+json" } });
  if (!response.ok) throw new Error(`${url}: HTTP ${response.status}`);
  return response.json();
}

export async function main(args) {
  const options = {};
  for (let i = 0; i < args.length; i++) {
    if (!["--manifest", "--revision"].includes(args[i]) || !args[i + 1]) throw new Error(`unknown or incomplete argument ${args[i]}`);
    options[args[i].slice(2)] = args[++i];
  }
  if (options.manifest && !options.revision) throw new Error("a local manifest requires its source --revision");
  const revision = options.revision ?? (await json(`https://api.github.com/repos/${repository}/commits/main`)).sha;
  const source = sourceModule(revision);
  const manifest = validate(options.manifest
    ? JSON.parse(readFileSync(options.manifest, "utf8"))
    : await json(`https://raw.githubusercontent.com/${repository}/${revision}/${manifestPath}`));
  const root = new URL("../src/content/", import.meta.url);
  writeFileSync(new URL("coverage.json", root), JSON.stringify(manifest, null, 2) + "\n");
  writeFileSync(new URL("conformance_source.ts", root), source);
  console.log(`Imported ${Object.keys(manifest.arms).length} panel arms at ${repository}@${revision}`);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main(process.argv.slice(2)).catch(error => { console.error(error.message); process.exitCode = 1; });
}
